"""The synthesis lines only the X engine ([simulation] engine = x) adds to the locked
script (runner.YOSYS_TEMPLATE's ``{x_map}``): its latches as the library's latch
cells. ``dfflibmap`` maps flip-flops only (``t:$_DFF* t:$_SDFF*``, Yosys 0.61), so a
design's latches would stay Yosys ``$_DLATCH_*`` cells, which no cell map models.

``dfflegalize`` reduces every latch to the plain ones the library has (a reset or
set becomes gates on its enable and data, an enable of the other level an
inverter); a techmap then puts each on the library's cell (faultflow.pdk.roles
``latch``). A two-valued run has none of this: its script is the one it always was,
and a latch stays a cell it does not model."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Mapping

from faultflow.pdk.roles import LibraryRoles, RoleCell

# Yosys's plain latch cells (ports E, D, Q) and the enable level each opens at.
_YOSYS_LATCH = {"$_DLATCH_P_": "HIGH", "$_DLATCH_N_": "LOW"}


def latch_cells(cell_map: Mapping[str, Any]) -> dict[str, RoleCell]:
    """The library's cell for each Yosys plain latch it has one for."""
    roles = LibraryRoles(cell_map, None)
    found = {}
    for yosys, level in _YOSYS_LATCH.items():
        cell = roles.latch(level)
        if cell is not None:
            found[yosys] = cell
    return found


def latch_techmap(cells: Mapping[str, RoleCell]) -> str:
    """A Yosys techmap putting each plain latch on its library cell."""
    out = ["// Generated by FaultFlow (faultflow.pdk.x_synth): the X engine's latches."]
    for yosys, cell in sorted(cells.items()):
        conns = [
            f".{cell.pins['en']}(E)",
            f".{cell.pins['d']}(D)",
            f".{cell.pins['q']}(Q)",
            *(f".{pin}(1'b{value})" for pin, value in sorted(cell.ties.items())),
        ]
        out += [
            f"module \\{yosys} (input E, input D, output Q);",
            f"  {cell.cell} _TECHMAP_REPLACE_ ({', '.join(conns)});",
            "endmodule",
        ]
    return "\n".join(out) + "\n"


def x_map_lines(cells: Mapping[str, RoleCell], map_path: Path) -> str:
    """The script lines (empty without any latch cell: a design's latch then stays
    a cell no map models, which fails loudly)."""
    if not cells:
        return ""
    legal = " ".join(f"-cell {yosys} x" for yosys in sorted(cells))
    return f"dfflegalize {legal} t:$_DLATCH*\ntechmap -map {map_path}\n"
