"""The synthesis lines only the X engine ([simulation] engine = x) adds to the locked
script (runner.YOSYS_TEMPLATE's ``{x_tribuf}`` and ``{x_map}``): its latches and
tristate buffers as the library's cells.

``dfflibmap`` maps flip-flops only (``t:$_DFF* t:$_SDFF*``, Yosys 0.61), so a
design's latches would stay Yosys ``$_DLATCH_*`` cells, which no cell map models.
``dfflegalize`` reduces every latch to the plain ones the library has (a reset or
set becomes gates on its enable and data, an enable of the other level an
inverter); a techmap then puts each on the library's cell (faultflow.pdk.roles
``latch``).

Without ``tribuf`` (right after ``proc``), ``synth``'s optimisations read a ``1'bz``
as a don't-care and turn ``oe ? a : 1'bz`` into ``a``, merging a bus's drivers. With
it, each becomes a ``$_TBUF_``, which the same techmap puts on the library's
tristate buffer (an inverter on its data or enable where the cell's differ).

A two-valued run has none of this: its script is the one it always was, and a latch
or tristate stays a cell it does not model."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping

from faultflow.pdk.roles import LIBRARY_KEY, LibraryRoles, RoleCell, _concrete, _sized

# Yosys's plain latch cells (ports E, D, Q) and the enable level each opens at.
_YOSYS_LATCH = {"$_DLATCH_P_": "HIGH", "$_DLATCH_N_": "LOW"}


def latch_cells(cell_map: Mapping[str, Any]) -> dict[str, RoleCell]:
    """The library's cell for each Yosys plain latch it has one for."""
    roles = LibraryRoles(cell_map, None)
    found = {}
    for yosys, level in _YOSYS_LATCH.items():
        cell = roles.latch(level)
        if cell is not None:
            found[yosys] = cell
    return found


@dataclass(frozen=True)
class TristateCell:
    """The library's tristate buffer: ``output`` drives ``data`` (inverted with
    ``invert``) while ``enable`` is high (``active_high``) or low."""

    cell: str
    data: str
    enable: str
    output: str
    active_high: bool
    invert: bool


def tristate_cell(cell_map: Mapping[str, Any]) -> TristateCell | None:
    """The library's tristate buffer for Yosys's ``$_TBUF_``: a non-inverting one
    first, then one enabled high, then a sized one."""
    fits = []
    for pattern, entry in cell_map.items():
        if (
            not isinstance(entry, Mapping)
            or pattern.startswith(("$", "\\"))
            or entry.get("node_type") != "TBUF"
            or entry.get(LIBRARY_KEY)
            or not isinstance(entry.get("tbuf"), Mapping)
        ):
            continue
        tbuf = entry["tbuf"]
        high = tbuf.get("level", "HIGH") == "HIGH"
        invert = bool(tbuf.get("invert", False))
        fits.append((invert, not high, not _sized(pattern, entry), pattern, entry))
    if not fits:
        return None
    invert, low, _, pattern, entry = sorted(fits, key=lambda f: f[:4])[0]
    tbuf = entry["tbuf"]
    return TristateCell(
        _concrete(pattern, entry),
        str(tbuf["data"]),
        str(tbuf["enable"]),
        str(tbuf["output"]),
        not low,
        invert,
    )


def _tristate_module(t: TristateCell) -> list[str]:
    data = "A" if not t.invert else "a_n"
    enable = "E" if t.active_high else "e_n"
    lines = ["module \\$_TBUF_ (input A, input E, output Y);"]
    if t.invert:
        lines.append("  wire a_n = ~A;")
    if not t.active_high:
        lines.append("  wire e_n = ~E;")
    lines += [
        f"  {t.cell} _TECHMAP_REPLACE_ (.{t.data}({data}), .{t.enable}({enable}), "
        f".{t.output}(Y));",
        "endmodule",
    ]
    return lines


def latch_techmap(
    cells: Mapping[str, RoleCell], tristate: TristateCell | None = None
) -> str:
    """A Yosys techmap putting each plain latch, and a tristate buffer, on its
    library cell."""
    out = [
        "// Generated by FaultFlow (faultflow.pdk.x_synth): the X engine's latches "
        "and tristate buffers."
    ]
    if tristate is not None:
        out += _tristate_module(tristate)
    for yosys, cell in sorted(cells.items()):
        conns = [
            f".{cell.pins['en']}(E)",
            f".{cell.pins['d']}(D)",
            f".{cell.pins['q']}(Q)",
            *(f".{pin}(1'b{value})" for pin, value in sorted(cell.ties.items())),
        ]
        out += [
            f"module \\{yosys} (input E, input D, output Q);",
            f"  {cell.cell} _TECHMAP_REPLACE_ ({', '.join(conns)});",
            "endmodule",
        ]
    return "\n".join(out) + "\n"


def x_map_lines(
    cells: Mapping[str, RoleCell], map_path: Path, tristate: TristateCell | None = None
) -> str:
    """The script lines after dfflibmap (empty without any latch or tristate
    cell: a design's latch or tristate then stays a cell no map models, which
    fails loudly)."""
    lines = ""
    if cells:
        legal = " ".join(f"-cell {yosys} x" for yosys in sorted(cells))
        lines += f"dfflegalize {legal} t:$_DLATCH*\n"
    if cells or tristate is not None:
        # simplemap: the map's inverters (a coarse $not) as gates abc maps.
        lines += f"techmap -map {map_path}\nsimplemap\n"
    return lines
